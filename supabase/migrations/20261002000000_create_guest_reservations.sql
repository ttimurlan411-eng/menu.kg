-- Customer table reservations, made from a table's opaque QR code.
--
-- Customers have no account. The public menu deliberately works for signed-out
-- guests, and the only authentication in this project is the restaurant-staff
-- one, whose AuthGate routes any signed-in user into the admin area. A
-- reservation therefore follows the access model this project already proves for
-- table QR codes: an unguessable token is the credential, no table is readable
-- by anyone, and the database is the only thing that decides who sees what.
--
-- A guest is public.reservation_access.access_token: 244 bits of randomness
-- generated by Postgres itself. It is kept on the guest's own device and
-- presented to read or cancel that guest's reservations, so "My Reservations"
-- still works after the app is closed and reopened. Nothing about the token is
-- predictable, enumerable, or accepted as a url.
--
-- Deliberately NOT in this migration, because the project defines no rule for
-- them: opening hours, reservation duration, buffers between bookings, overlap
-- detection, party-size rules beyond the existing tables.capacity column, and
-- any staff-side management of reservations.
--
-- Deliberately NOT exposed, as with the public menu: restaurant, branch and
-- table ids, and every column the guest UI does not need.

-- public.tables is the only multi-tenant table that never got the composite
-- unique key the others have (branches, categories and menu_items all carry
-- `unique (id, restaurant_id)`). It is added here so reservations can reference
-- the table the same way categories reference menu items: through a composite
-- foreign key, which makes a table from another restaurant impossible to store
-- rather than merely unlikely. The key is implied by the primary key, so this
-- changes no existing row.
alter table public.tables
  add constraint tables_id_restaurant_id_key unique (id, restaurant_id);

create table public.reservation_access (
  access_token text primary key,
  created_at timestamptz not null default now()
);

comment on table public.reservation_access is
  'One row per guest who can reach their own reservations, addressed by an opaque unguessable token. Reached only through the guest_reservations and create_table_reservation functions; no table grant exists.';

create table public.reservations (
  id uuid primary key default gen_random_uuid(),
  access_token text not null,
  restaurant_id uuid not null,
  branch_id uuid not null,
  table_id uuid not null,
  reserved_date date not null,
  reserved_time time not null,
  guest_name text not null,
  guest_count integer not null default 1,
  status text not null default 'CONFIRMED',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reservations_access_token_fkey
    foreign key (access_token)
    references public.reservation_access (access_token)
    on delete cascade,
  constraint reservations_restaurant_id_fkey
    foreign key (restaurant_id)
    references public.restaurants (id)
    on delete restrict,
  constraint reservations_branch_id_restaurant_id_fkey
    foreign key (branch_id, restaurant_id)
    references public.branches (id, restaurant_id)
    on delete restrict,
  -- The composite key is what stops a table from another restaurant being used:
  -- a plain table_id would accept it, (table_id, restaurant_id) cannot.
  constraint reservations_table_id_restaurant_id_fkey
    foreign key (table_id, restaurant_id)
    references public.tables (id, restaurant_id)
    on delete restrict,
  constraint reservations_guest_name_check
    check (char_length(btrim(guest_name)) between 1 and 100),
  constraint reservations_guest_count_check check (guest_count > 0),
  constraint reservations_status_check check (status in ('CONFIRMED', 'CANCELLED'))
);

comment on table public.reservations is
  'A customer table reservation. Reachable only by the guest token that created it, through create_table_reservation, guest_reservations and cancel_guest_reservation.';

comment on column public.reservations.table_id is
  'The table whose QR code the guest scanned. Ids are never sent to the client; only display labels are.';

create index idx_reservations_access_token
  on public.reservations (access_token, reserved_date, reserved_time);

create index idx_reservations_restaurant_id
  on public.reservations (restaurant_id, reserved_date);

create index idx_reservations_table_id
  on public.reservations (table_id, reserved_date);

-- The single conflict rule that needs no business decision: one table cannot host
-- two parties at the same minute. Cancelled rows leave the index, so the slot
-- becomes bookable again. Every softer rule (duration, buffers, overlaps across
-- different times) depends on scheduling rules this project has not defined, so
-- it is left to a later migration rather than guessed at here.
create unique index idx_reservations_active_slot
  on public.reservations (table_id, reserved_date, reserved_time)
  where status = 'CONFIRMED';

create trigger set_reservations_updated_at
before update on public.reservations
for each row execute function public.set_updated_at();

alter table public.reservation_access enable row level security;
alter table public.reservations enable row level security;

-- No grants at all, to anon or to authenticated. The functions below are the
-- only way in, which is what stops one guest reading or cancelling another
-- guest's reservation, and stops staff-side table reads from handing out access
-- tokens. RLS is enabled on both tables so that stays true if a later migration
-- adds a grant.
revoke all on table public.reservation_access from public, anon, authenticated;
revoke all on table public.reservations from public, anon, authenticated;

-- Creates a reservation for the table whose QR code the guest scanned.
--
-- The QR token is the whole restaurant/branch/table context, exactly as in
-- public_menu_by_qr_token: the guest never sends or receives a restaurant,
-- branch or table id, and a token from another restaurant cannot be used to
-- reserve a table anywhere else. Returns the guest's access token together with
-- the created reservation, so a returning guest keeps one identity for all of
-- their reservations.
create or replace function public.create_table_reservation(
  p_qr_token text,
  p_reserved_date date,
  p_reserved_time time,
  p_guest_name text,
  p_guest_count integer,
  p_access_token text default null
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_token uuid;
  v_table public.tables%rowtype;
  v_restaurant public.restaurants%rowtype;
  v_branch public.branches%rowtype;
  v_guest_name text;
  v_guest_count integer;
  v_access_token text;
  v_reservation public.reservations%rowtype;
begin
  -- A malformed token is reported as "no reservation" instead of a cast error,
  -- so the public flow cannot be probed for database internals through error
  -- text. It is deliberately indistinguishable from an unknown token.
  if p_qr_token is null
    or pg_catalog.btrim(p_qr_token) !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
  then
    return null;
  end if;

  v_token := pg_catalog.btrim(p_qr_token)::uuid;

  select *
    into v_table
    from public.tables as t
   where t.qr_token = v_token
     and t.is_active
   limit 1;

  if not found then
    return null;
  end if;

  select *
    into v_restaurant
    from public.restaurants as r
   where r.id = v_table.restaurant_id
     and r.is_active;

  if not found then
    return null;
  end if;

  -- Re-checks that the branch belongs to the same restaurant as the table.
  select *
    into v_branch
    from public.branches as b
   where b.id = v_table.branch_id
     and b.restaurant_id = v_table.restaurant_id
     and b.is_active;

  if not found then
    return null;
  end if;

  v_guest_name := pg_catalog.btrim(coalesce(p_guest_name, ''));

  -- Only checks the project already knows: a guest count fits the table it is
  -- booked for, and the requested day has not passed. Opening hours, minimum or
  -- maximum party sizes and slot spacing are not defined anywhere in this
  -- project, so they are not invented here.
  if p_reserved_date is null
    or p_reserved_date < current_date
    or p_reserved_time is null
    or char_length(v_guest_name) not between 1 and 100
    or p_guest_count is null
    or p_guest_count < 1
    or p_guest_count > v_table.capacity
  then
    raise exception 'invalid_reservation_request' using errcode = 'P0001';
  end if;

  v_guest_count := p_guest_count;

  -- Reuses the guest's own token when they already have one, so a second
  -- reservation lands in the same "My Reservations" list. A token that does not
  -- exist, or that the guest does not have yet, mints a new one: 244 bits from
  -- Postgres, so it cannot be guessed or enumerated, and nothing in the request
  -- can influence or predict it.
  select pg_catalog.btrim(p_access_token)
    into v_access_token
   where exists (
     select 1
       from public.reservation_access as access
      where access.access_token = pg_catalog.btrim(p_access_token)
   );

  if v_access_token is null then
    v_access_token :=
      pg_catalog.gen_random_uuid()::text || pg_catalog.gen_random_uuid()::text;

    insert into public.reservation_access (access_token)
    values (v_access_token);
  end if;

  -- The exact-slot unique index rejects a double booking of the same minute with
  -- a unique_violation, which the client shows as "that time is already taken".
  -- A failed insert leaves the new access token behind, which is harmless: a
  -- token with no reservations is indistinguishable from a new guest.
  insert into public.reservations (
    access_token,
    restaurant_id,
    branch_id,
    table_id,
    reserved_date,
    reserved_time,
    guest_name,
    guest_count
  )
  values (
    v_access_token,
    v_restaurant.id,
    v_branch.id,
    v_table.id,
    p_reserved_date,
    p_reserved_time,
    v_guest_name,
    v_guest_count
  )
  returning * into v_reservation;

  return jsonb_build_object(
    'access_token', v_access_token,
    'reservation', jsonb_build_object(
      'id', v_reservation.id,
      'restaurant_name', v_restaurant.name,
      'branch_name', v_branch.name,
      'table', jsonb_build_object(
        'number', v_table.table_number,
        'name', v_table.name
      ),
      'reserved_date', v_reservation.reserved_date,
      'reserved_time', v_reservation.reserved_time,
      'guest_name', v_reservation.guest_name,
      'guest_count', v_reservation.guest_count,
      'status', v_reservation.status,
      'created_at', v_reservation.created_at
    )
  );
end;
$$;

comment on function public.create_table_reservation(text, date, time, text, integer, text) is
  'Creates a reservation for the table resolved from p_qr_token. Reuses p_access_token when the guest already has one and mints a new token otherwise, returning it with the reservation. Returns null when the token is malformed or its table, branch or restaurant is inactive. Raises a unique_violation for an already booked slot.';

-- The guest's own reservations, addressed by the opaque access token.
create or replace function public.guest_reservations(p_access_token text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_reservations jsonb;
begin
  -- An unknown, empty or malformed token returns an empty list rather than an
  -- error, so the function cannot be used to find out which tokens exist. Every
  -- row is filtered by the token itself, so no guest can read another's
  -- reservations, and the restaurant, branch and table of a reservation are
  -- reported as display labels only.
  if p_access_token is null or pg_catalog.btrim(p_access_token) = '' then
    return jsonb_build_object('reservations', '[]'::jsonb);
  end if;

  select coalesce(
           jsonb_agg(
             jsonb_build_object(
               'id', reservation.id,
               'restaurant_name', restaurant.name,
               'branch_name', branch.name,
               'table', jsonb_build_object(
                 'number', reserved_table.table_number,
                 'name', reserved_table.name
               ),
               'reserved_date', reservation.reserved_date,
               'reserved_time', reservation.reserved_time,
               'guest_name', reservation.guest_name,
               'guest_count', reservation.guest_count,
               'status', reservation.status,
               'created_at', reservation.created_at
             )
             order by reservation.reserved_date, reservation.reserved_time
           ),
           '[]'::jsonb
         )
    into v_reservations
    from public.reservations as reservation
    join public.restaurants as restaurant
      on restaurant.id = reservation.restaurant_id
    join public.branches as branch
      on branch.id = reservation.branch_id
    join public.tables as reserved_table
      on reserved_table.id = reservation.table_id
   where reservation.access_token = pg_catalog.btrim(p_access_token);

  return jsonb_build_object('reservations', v_reservations);
end;
$$;

comment on function public.guest_reservations(text) is
  'Returns the reservations created with this opaque guest access token, or an empty list for an unknown token. Exposes no restaurant, branch or table ids.';

-- Cancels one of the guest's own reservations.
create or replace function public.cancel_guest_reservation(
  p_access_token text,
  p_reservation_id uuid
)
returns boolean
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  -- Scoped by the guest's own token, so a reservation id belonging to another
  -- guest matches nothing and returns false. Only the status can change: there
  -- is no path here that edits the table, the branch, the restaurant, the guest,
  -- or the requested slot, and a cancelled reservation cannot be cancelled
  -- again.
  update public.reservations
     set status = 'CANCELLED'
   where id = p_reservation_id
     and access_token = pg_catalog.btrim(p_access_token)
     and status = 'CONFIRMED';

  return found;
end;
$$;

comment on function public.cancel_guest_reservation(text, uuid) is
  'Cancels one of this guest token''s confirmed reservations and returns whether a row changed. Never touches a reservation of another guest.';

-- Defence in depth: the reservation tables stay unreadable and unwritable for
-- anon and for signed-in users, so these three functions remain the only path
-- into guest reservation data.
revoke all on function public.create_table_reservation(text, date, time, text, integer, text) from public, anon;
revoke all on function public.guest_reservations(text) from public, anon;
revoke all on function public.cancel_guest_reservation(text, uuid) from public, anon;

grant execute on function public.create_table_reservation(text, date, time, text, integer, text)
  to anon, authenticated;
grant execute on function public.guest_reservations(text)
  to anon, authenticated;
grant execute on function public.cancel_guest_reservation(text, uuid)
  to anon, authenticated;

-- Defence in depth: the core tables keep no reservation-adjacent access.
revoke all on table public.tables from anon;
